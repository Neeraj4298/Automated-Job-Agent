ALL_AGENTS = CHROME_WINDOWS + CHROME_MACOS + CHROME_LINUX + FIREFOX_WINDOWS

# Weight pool so Chrome/Windows is most common (~60% of real traffic)
WEIGHTED_AGENTS = (
    CHROME_WINDOWS * 6
    + CHROME_MACOS * 3
    + CHROME_LINUX * 2
    + FIREFOX_WINDOWS * 1
)

# Common viewport sizes (width, height) in the real-user distribution
VIEWPORTS = [
    {"width": 1920, "height": 1080},
    {"width": 1366, "height": 768},
    {"width": 1536, "height": 864},
    {"width": 1440, "height": 900},
    {"width": 1280, "height": 800},
]

VIEWPORT_WEIGHTS = [30, 25, 20, 15, 10]  # approximate % in real traffic


def get_random_ua() -> str:
    """Return a randomly chosen, weighted User-Agent string."""
    return random.choice(WEIGHTED_AGENTS)


def get_random_viewport() -> dict:
    """Return a realistic viewport dict for Playwright."""
    return random.choices(VIEWPORTS, weights=VIEWPORT_WEIGHTS, k=1)[0]
